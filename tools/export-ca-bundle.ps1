<#
  Exports the Windows certificate stores into a PEM bundle that Node can trust.

  Why this exists: this network terminates TLS with Zscaler. The Zscaler root is
  installed in the Windows certificate store, so browsers and Git (which uses the
  schannel backend) work. Node ships its own CA list and ignores the Windows
  store, so every HTTPS call from Node fails with UNABLE_TO_GET_ISSUER_CERT_LOCALLY.

  The fix is to give Node the Windows roots. The alternative that turns up in
  search results - setting NODE_TLS_REJECT_UNAUTHORIZED=0 - disables certificate
  verification for the whole process, including the requests that carry the PAT,
  and must not be used.

  Output is machine-specific and gitignored. Re-run after corporate CA changes.
#>
[CmdletBinding()]
param(
    [string]$OutFile = (Join-Path $PSScriptRoot '..\certs\windows-ca-bundle.pem')
)

$ErrorActionPreference = 'Stop'

$dir = Split-Path -Parent $OutFile
if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Force -Path $dir | Out-Null }

$stores = @(
    'Cert:\LocalMachine\Root', 'Cert:\LocalMachine\CA',
    'Cert:\CurrentUser\Root', 'Cert:\CurrentUser\CA'
)

$seen = @{}
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('# Generated by tools/export-ca-bundle.ps1 - do not edit by hand.')
[void]$sb.AppendLine("# Generated $(Get-Date -Format o)")

foreach ($store in $stores) {
    foreach ($cert in (Get-ChildItem $store -ErrorAction SilentlyContinue)) {
        if ($seen.ContainsKey($cert.Thumbprint)) { continue }
        $seen[$cert.Thumbprint] = $true
        [void]$sb.AppendLine("# $($cert.Subject)")
        [void]$sb.AppendLine('-----BEGIN CERTIFICATE-----')
        [void]$sb.AppendLine([Convert]::ToBase64String($cert.RawData, 'InsertLineBreaks'))
        [void]$sb.AppendLine('-----END CERTIFICATE-----')
    }
}

Set-Content -Path $OutFile -Value $sb.ToString() -Encoding ascii

$zscaler = $seen.Count
Write-Host "Exported $($seen.Count) unique certificates to $OutFile"
$hasInterceptor = Get-ChildItem 'Cert:\LocalMachine\Root' -ErrorAction SilentlyContinue |
    Where-Object { $_.Subject -match 'Zscaler|Netskope|Palo Alto|Blue Coat|Forcepoint' } |
    Select-Object -First 1
if ($hasInterceptor) {
    Write-Host "Detected TLS interception root: $($hasInterceptor.Subject)"
}
Write-Host 'Verify with: npm run tls:check'
